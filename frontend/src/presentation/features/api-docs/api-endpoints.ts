// The API as the frontend uses it, and as the backend has built it. Written from origin/dev
// (frontend/docs/backend-contract.md, application/services.ts) and the backend's dev branch.
// Keep it in step with the contract: a route here that the contract does not have is a mistake.

// built: the backend's dev branch has it. branch: written on a backend feature branch, not merged.
// proposed: no backend code yet; the frontend uses the in-memory mock for it today.
export type ApiStatus = 'built' | 'branch' | 'proposed'

// real: the frontend calls it when VITE_API_URL is set. mock: the mock stands in until it is built.
// unused: the backend has it, the frontend does not call it.
export type FrontendUse = 'real' | 'mock' | 'unused'

export type ApiMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'

export type ApiArea =
  | 'System'
  | 'Session'
  | 'PIN'
  | 'Dashboard'
  | 'Orders'
  | 'Menu'
  | 'Stock'
  | 'Customers'
  | 'Schedule'
  | 'Team'
  | 'Kitchen'
  | 'Live console'
  | 'Reports'

export type ApiEndpoint = {
  id: string
  area: ApiArea
  method: ApiMethod
  path: string
  status: ApiStatus
  frontend: FrontendUse
  // The screen or service that calls it.
  screen: string
  summary: string
  request?: string
  response: string
  rules: string[]
  errors?: string[]
}

